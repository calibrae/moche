"""Reads `cargo metadata` JSON on stdin, prints THIRD_PARTY.md for a crate's normal deps."""
import hashlib, json, os, re, sys

root_name = sys.argv[1]
meta = json.load(sys.stdin)
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(i for i, p in pkgs.items() if p["name"] == root_name)

seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        # normal (non-dev, non-build-only) dependencies that apply to the platform
        if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

ours = {i for i in seen if pkgs[i]["source"] is None}
third = sorted((pkgs[i] for i in seen - ours), key=lambda p: (p["name"], p["version"]))

LIC = re.compile(r"^(licen[cs]e|copying|unlicense|notice)([-_.].*)?$", re.I)

def texts(pkg):
    d = os.path.dirname(pkg["manifest_path"])
    found = []
    for dirpath, dirs, files in os.walk(d):
        depth = dirpath[len(d):].count(os.sep)
        if depth > 1:
            dirs[:] = []
            continue
        for f in sorted(files):
            if LIC.match(f) and not f.endswith((".rs", ".toml")):
                with open(os.path.join(dirpath, f), "rb") as fh:
                    found.append(fh.read().decode("utf-8", "replace").strip("\n"))
    return found

groups = {}
rows = []
for p in third:
    ts = texts(p)
    for t in ts:
        h = hashlib.sha256(re.sub(r"\s+", " ", t).encode()).hexdigest()
        groups.setdefault(h, {"text": t, "crates": []})["crates"].append(f'{p["name"]} {p["version"]}')
    rows.append((p, len(ts)))

o = []
w = o.append
w("# Third-party licences\n")
w(f"Generated by `tools/third-party.sh` (`cargo metadata --filter-platform aarch64-apple-ios` over `{root_name}`).")
w("Do not edit by hand. moche itself is `MIT OR Apache-2.0` (see `LICENSE-MIT`, `LICENSE-APACHE`).")
w("Security notes and how to report issues: see `SECURITY.md`.\n")
w("## Crates\n")
w("| Crate | Version | Licence |")
w("|---|---|---|")
for p, n in rows:
    lic = (p["license"] or "see licence file").replace("|", "\\|")
    w(f'| {p["name"]} | {p["version"]} | {lic}{"" if n else " (no licence file in the crate)"} |')
w("\n## Licence texts\n")
w("Identical texts are listed once, with every crate they come from.\n")
for g in sorted(groups.values(), key=lambda g: g["crates"][0]):
    w("### " + ", ".join(g["crates"]) + "\n")
    w("```text")
    w(g["text"])
    w("```\n")
sys.stdout.write("\n".join(o))
